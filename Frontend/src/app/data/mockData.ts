export const getNfrById = (id: string | null) => nfrs.find(n => n.recordId === id);
export const getNfrByMantisId = (mantisId: string | null) => nfrs.find(n => n.mantisId === mantisId);
export const getKnockById = (id: string | null) => knocks.find(k => k.recordId === id);
